// Writes capture-bundle.js: the page-injected capture engine as one string, the
// same bundle the extension, the CLI and the MCP server inject. Wrangler runs this
// before `wrangler dev` and `wrangler deploy` (build.command in wrangler.jsonc).
import { readFile, writeFile } from 'node:fs/promises'
import { captureBundle } from '../../../packages/capture/inject.mjs'

const { version } = JSON.parse(
  await readFile(new URL('../../../package.json', import.meta.url), 'utf8'),
)
await writeFile(
  new URL('capture-bundle.js', import.meta.url),
  `// Generated by bundle.mjs; do not edit.\nexport default ${JSON.stringify(await captureBundle())}\nexport const version = ${JSON.stringify(version)}\n`,
)
